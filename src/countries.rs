pub fn name_by_iso2(iso: &str) -> String {
    COUNTRIES
        .iter()
        .find(|(code, _)| code.eq_ignore_ascii_case(iso))
        .map(|(_, name)| name.to_string())
        .unwrap_or_default()
}

/// The flag emoji of a two letter country code, or nothing for other input.
pub fn flag_emoji(iso: &str) -> String {
    let bytes = iso.as_bytes();
    if bytes.len() != 2 || !bytes.iter().all(|b| b.is_ascii_uppercase()) {
        return String::new();
    }
    if iso == "FT" {
        return "\u{1F3F4}\u{200D}\u{2620}\u{FE0F}".to_string();
    }
    bytes
        .iter()
        .filter_map(|b| char::from_u32(0x1F1E6 + (*b - b'A') as u32))
        .collect()
}
